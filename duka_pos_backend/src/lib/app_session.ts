/**
 * The till's own session, issued after an email-verified link.
 *
 * WHAT THIS IS FOR
 * The owner taps Verify, the Keycloak account is created from the shop they
 * already set up, a 6-digit code proves they own the email, and the device is
 * then signed in — without a browser round-trip and without a password the
 * owner ever had to invent. Something has to carry that sign-in, and it is
 * this token.
 *
 * WHAT THIS DELIBERATELY IS NOT
 * It is not a second identity authority. It is minted only by `/auth/verify`
 * and `/auth/refresh`, only after the email has been verified, only for the
 * Keycloak subject that was just verified, and only for a short lifetime. It
 * is accepted by `authMiddleware` on a small allowlist of paths, so it can
 * push a shop's catalogue and read its own reports but cannot move money, file
 * a tax invoice, or touch platform administration — those still require the
 * full browser sign-in against the issuer.
 *
 * Signed with HMAC-SHA256 rather than added as a dependency-free RS256
 * implementation: the secret is generated by the operator, lives only in this
 * process's environment, and rotating it invalidates every outstanding
 * session, which is exactly the revocation property a stolen device needs.
 */

import { createHmac, randomUUID, timingSafeEqual } from 'node:crypto';

export const APP_SESSION_ISSUER = 'simplesales-app';
export const APP_SESSION_TOKEN_USE = 'app_session';
export const APP_SESSION_TTL_MS = 12 * 60 * 60 * 1000;
const APP_SESSION_MAX_LIFETIME_MS = 24 * 60 * 60 * 1000;
const CLOCK_SKEW_SECONDS = 60;

/** The paths an app session may reach. Anything not listed here still requires
 * a token minted by the identity server itself. */
const ALLOWED_PATH_PREFIXES = ['/tenant/', '/products/', '/reports/'] as const;

export type AppSessionClaims = {
  sub: string;
  email: string;
  email_verified: boolean;
  token_use: string;
  iat: number;
  exp: number;
  jti: string;
  iss: string;
  aud?: string;
};

export type IssueAppSessionInput = {
  subject: string;
  email: string;
  secret: string;
  ttlMs?: number;
  audience?: string;
  now?: Date;
};

function base64url(input: Buffer | string): string {
  return Buffer.from(input as never)
    .toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
}

function decodeBase64url(value: string): Buffer {
  return Buffer.from(value.replace(/-/g, '+').replace(/_/g, '/'), 'base64');
}

function sign(data: string, secret: string): string {
  return createHmac('sha256', secret).update(data, 'utf8').digest('base64url');
}

export function issueAppSession(input: IssueAppSessionInput): { token: string; claims: AppSessionClaims } {
  const now = input.now ?? new Date();
  const ttlMs = Math.min(input.ttlMs ?? APP_SESSION_TTL_MS, APP_SESSION_MAX_LIFETIME_MS);
  const claims: AppSessionClaims = {
    sub: input.subject,
    email: input.email,
    // Not a claim we take the client's word for: the endpoint that calls this
    // has just verified the address, and everything downstream re-checks it.
    email_verified: true,
    token_use: APP_SESSION_TOKEN_USE,
    iat: Math.floor(now.getTime() / 1000),
    exp: Math.floor((now.getTime() + ttlMs) / 1000),
    jti: randomUUID(),
    iss: APP_SESSION_ISSUER,
    ...(input.audience ? { aud: input.audience } : {}),
  };
  const header = base64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
  const payload = base64url(JSON.stringify(claims));
  const body = `${header}.${payload}`;
  return { token: `${body}.${sign(body, input.secret)}`, claims };
}

/**
 * Verifies one of ours. Returns null for anything else — including a Keycloak
 * token, which the caller must pass to the JWKS verifier instead.
 *
 * Every failure returns the same null: an expired session and a forged one are
 * indistinguishable from the outside, which is the only answer that does not
 * teach an attacker which half of their guess was right.
 */
export function verifyAppSession(
  token: string,
  secrets: readonly string[],
  now: Date = new Date(),
): AppSessionClaims | null {
  if (secrets.length === 0) return null;
  const parts = token.split('.');
  if (parts.length !== 3) return null;

  const [headerRaw, payloadRaw, signature] = parts;
  let header: { alg?: unknown; typ?: unknown };
  let claims: AppSessionClaims;
  try {
    header = JSON.parse(decodeBase64url(headerRaw).toString('utf8'));
    claims = JSON.parse(decodeBase64url(payloadRaw).toString('utf8'));
  } catch {
    return null;
  }
  if (header?.alg !== 'HS256' || header?.typ !== 'JWT') return null;
  if (claims.token_use !== APP_SESSION_TOKEN_USE) return null;
  // Minted only by a verified link, and every consumer treats the address as
  // verified — so a token that claims otherwise is not one of ours.
  if (claims.email_verified !== true) return null;
  if (claims.iss !== APP_SESSION_ISSUER) return null;
  if (typeof claims.sub !== 'string' || !claims.sub) return null;
  if (typeof claims.email !== 'string' || !claims.email) return null;

  const nowSeconds = Math.floor(now.getTime() / 1000);
  if (typeof claims.exp !== 'number' || claims.exp <= nowSeconds) return null;
  if (typeof claims.iat !== 'number' || claims.iat > nowSeconds + CLOCK_SKEW_SECONDS) return null;
  // A session longer than a day is not a session; it is a password that does
  // not expire and lives in a phone's storage.
  if (claims.exp - claims.iat > APP_SESSION_MAX_LIFETIME_MS / 1000) return null;

  const signed = `${headerRaw}.${payloadRaw}`;
  for (const secret of secrets) {
    const expected = Buffer.from(sign(signed, secret), 'utf8');
    const presented = Buffer.from(signature, 'utf8');
    if (expected.length === presented.length && timingSafeEqual(expected, presented)) {
      return claims;
    }
  }
  return null;
}

export function isAppSessionAllowed(path: string): boolean {
  return ALLOWED_PATH_PREFIXES.some((prefix) => path.startsWith(prefix));
}

/** For the route test that proves the allowlist has not quietly grown. */
export function appSessionAllowedPrefixes(): readonly string[] {
  return ALLOWED_PATH_PREFIXES;
}
